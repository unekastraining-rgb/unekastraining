export type ProbeStage =
  | "foundation"
  | "guided"
  | "supported"
  | "variation"
  | "independent"
  | "transfer"
  | "recall";

export type Probe = {
  id: string;
  factor: string;
  title: string;
  presentation: string;
  prompt: string;
  choices: { id: string; label: string }[];
  correctChoiceId: string;
  difficulty: number;
  performanceKind: "recognition" | "recall" | "application" | "explanation" | "production";
  why: string;
  /** One step in the adaptable progression. Not a learning-style label. */
  stage: ProbeStage;
  conceptLabel: string;
  /** Unset on recall and execution checks so writing does not distort every measurement. */
  explanationPrompt: string | null;
  /** Optional support. Absent when a hint would invalidate unaided recall. */
  hint: string | null;
  workedExample: string | null;
  soundPhrases: string[];
  unsoundPhrases: string[];
  /** What this probe can support. It does not assign the difficulty by itself. */
  difficultyFocus: "concept" | "sequence" | "structure" | "differentiation" | "coordination" | "precision" | "independence" | "transfer" | "retention";
  subject?: "python" | "math";
  /** choice = recognize an answer. order and assign = the learner builds it. */
  responseMode?: "choice" | "order" | "assign";
  /** Correct order is this array's order. */
  arrange?: { id: string; label: string }[];
  slots?: { id: string; label: string }[];
  pieces?: { id: string; label: string; slotId: string }[];
};

