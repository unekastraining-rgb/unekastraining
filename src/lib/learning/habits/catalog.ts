export function probeById(id: string): Probe | undefined {
  return PROBES.find((p) => p.id === id) ?? TASK_PROBES.find((p) => p.id === id);
}

export function nextProbe(input: {
  completedIds: string[];
  difficulty: number;
}): Probe | null {
  const pending = PROBES.filter(
    (p) => !input.completedIds.includes(p.id) && p.difficulty <= input.difficulty,
  );
  return pending[0] ?? PROBES.find((p) => !input.completedIds.includes(p.id)) ?? null;
}
